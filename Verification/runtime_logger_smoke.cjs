const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root,'Packages/com.runtime.ai-agent/Runtime/Diagnostics/Resources/AgentTrace/viewer.js.txt'),'utf8');
new vm.Script(source);
const body = source.slice(source.indexOf('  function parseJson('),source.indexOf('  function block('));
const {toolInput,readableJson} = new Function(body + '\nreturn {toolInput,readableJson};')();
const code = 'async {\n await engine.wait(1)\n}\n// <img src=x onerror=bad>';
assert.deepEqual(toolInput(JSON.stringify({definition:JSON.stringify({id:'tap',code})})),['Flecs Script: tap',code,'flecs']);
assert.deepEqual(toolInput(JSON.stringify({edit:JSON.stringify({component:'Scale',expression:'{2,2,2}'})})),['Flecs expression: Scale','{2,2,2}','flecs']);
const creation = {id:'Bunny',recipe:{version:4,parts:[]}};
assert.deepEqual(JSON.parse(readableJson(JSON.stringify({creation:JSON.stringify(creation)}))).creation,creation);
assert.deepEqual(toolInput(JSON.stringify({code})),['Flecs Script',code,'flecs']);
assert.deepEqual(toolInput(JSON.stringify({expression:'PoseOffset, (PoseTarget, $target)'})),['Flecs query','PoseOffset, (PoseTarget, $target)','query']);
assert.equal(toolInput('{bad')[2],'json');
const report = {passed:true,checkedUtc:new Date().toISOString(),checks:['Viewer source parses','Independent behavior source and expression edits retain exact text and select Flecs highlighting','Nested creation data becomes readable JSON','Existing Script/query inputs remain compatible','Malformed nested input falls back safely'],limits:['Pure formatter checks, not a new visual browser inspection']};
fs.writeFileSync(path.join(root,'Verification/runtime-logger-checks.json'),JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify(report,null,2));
