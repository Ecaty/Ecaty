using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Reflection;
using System.Text;
using Ecaty.Flecs;
using UnityEngine;

namespace Ecaty
{
    /// <summary>
    /// Gallery tuning values as Flecs Script. In the Editor, Gallery.asset (GalleryLayoutProfile) is the authoring UI and is
    /// exported to GalleryConfig.flecs; players ship only that script. Both load through the same Flecs path into a runtime
    /// profile copy, so the Editor exercises the build path.
    /// </summary>
    public static class GalleryConfigScript
    {
        public const string ScriptName = "GalleryConfig", Entity = "GalleryConfig", Component = "GalleryProfile";
        public const string AssetPath = "Assets/_Features/Gallery/Gallery.asset", ScriptPath = "Assets/_Features/Gallery/GalleryConfig.flecs";
        static readonly CultureInfo Invariant = CultureInfo.InvariantCulture;

        static IEnumerable<FieldInfo> Fields() => typeof(GalleryLayoutProfile).GetFields(BindingFlags.Public | BindingFlags.Instance)
            .Where(f => !f.IsNotSerialized && (f.FieldType == typeof(float) || f.FieldType == typeof(int) || f.FieldType == typeof(bool) || f.FieldType.IsEnum || f.FieldType == typeof(Color)));
        static string TypeName(Type t) => t == typeof(float) ? "f32" : t == typeof(bool) ? "bool" : t == typeof(Color) ? "GalleryColor" : "i32";
        static string Num(float v) => float.IsFinite(v) ? v.ToString("0.#########", Invariant) : "0";
        static string Value(object v) => v switch
        {
            float f => Num(f),
            bool b => b ? "true" : "false",
            Color c => $"{{r: {Num(c.r)}, g: {Num(c.g)}, b: {Num(c.b)}, a: {Num(c.a)}}}",
            Enum e => Convert.ToInt32(e, Invariant).ToString(Invariant),
            int i => i.ToString(Invariant),
            _ => throw new NotSupportedException(v?.GetType().Name)
        };

        public static string Generate(GalleryLayoutProfile profile)
        {
            var fields = Fields().ToArray();
            var s = new StringBuilder();
            s.Append("// Generated from Gallery.asset in the Editor. Tune Gallery.asset; do not edit this file.\n");
            s.Append("struct GalleryColor(r: f32, g: f32, b: f32, a: f32)\n");
            s.Append("struct ").Append(Component).Append('(').Append(string.Join(", ", fields.Select(f => f.Name + ": " + TypeName(f.FieldType)))).Append(")\n");
            s.Append(Entity).Append(" {\n  ").Append(Component).Append(": {\n");
            for (int i = 0; i < fields.Length; i++) s.Append("    ").Append(fields[i].Name).Append(": ").Append(Value(fields[i].GetValue(profile))).Append(i < fields.Length - 1 ? ",\n" : "\n");
            s.Append("  }\n}\n");
            return s.ToString();
        }

        /// <summary>Loads the script into Flecs and copies the resulting component into <paramref name="target"/>.</summary>
        public static void Load(FlecsSession session, string source, GalleryLayoutProfile target)
        {
            session.SetManagedScript(ScriptName, source);
            string json = session.ComponentJson(session.Lookup(Entity), Component);
            if (string.IsNullOrEmpty(json)) throw new InvalidOperationException("Gallery config script did not produce " + Component + ".");
            JsonUtility.FromJsonOverwrite(json, target);
        }

#if UNITY_EDITOR
        public static GalleryLayoutProfile EditorAsset => UnityEditor.AssetDatabase.LoadAssetAtPath<GalleryLayoutProfile>(AssetPath);

        /// <summary>Writes GalleryConfig.flecs when it differs from the asset. Returns true when the file changed.</summary>
        public static bool Export(GalleryLayoutProfile profile = null)
        {
            profile ??= EditorAsset;
            if (!profile) return false;
            string source = Generate(profile), full = System.IO.Path.GetFullPath(ScriptPath);
            if (System.IO.File.Exists(full) && System.IO.File.ReadAllText(full) == source) return false;
            System.IO.File.WriteAllText(full, source);
            UnityEditor.AssetDatabase.ImportAsset(ScriptPath);
            return true;
        }
        public static bool IsCurrent() { var p = EditorAsset; return p && System.IO.File.Exists(ScriptPath) && System.IO.File.ReadAllText(ScriptPath) == Generate(p); }
#endif
    }
}
