using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Reflection;
using System.Text;
using Runtime.Agents.UI;
using Runtime.Flecs;
using UnityEngine;

namespace Game
{
    /// <summary>
    /// Shared theme as Flecs Script. In the Editor, Theme.asset (GameTheme) is the authoring UI and is exported to
    /// ThemeConfig.flecs; players ship only that script. Both load through the same Flecs path into a runtime copy.
    /// </summary>
    public static class ThemeScript
    {
        public const string ScriptName = "ThemeConfig", Entity = "ThemeConfig", Component = "ThemeProfile";
        public const string ColorStruct = "ThemeColor", PaletteStruct = "ThemePalette";
        public const string AssetPath = "Assets/__Common/Theme/Theme.asset", ScriptPath = "Assets/__Common/Theme/ThemeConfig.flecs";
        static readonly CultureInfo Invariant = CultureInfo.InvariantCulture;

        static IEnumerable<FieldInfo> Fields(Type type) => type.GetFields(BindingFlags.Public | BindingFlags.Instance)
            .Where(f => !f.IsNotSerialized && (f.FieldType == typeof(float) || f.FieldType == typeof(Color) || f.FieldType == typeof(AgentUiPalette)));
        static string TypeName(Type t) => t == typeof(float) ? "f32" : t == typeof(Color) ? ColorStruct : PaletteStruct;
        static string Num(float v) => float.IsFinite(v) ? v.ToString("0.#########", Invariant) : "0";
        static string Value(object v) => v switch
        {
            float f => Num(f),
            Color c => $"{{r: {Num(c.r)}, g: {Num(c.g)}, b: {Num(c.b)}, a: {Num(c.a)}}}",
            _ => throw new NotSupportedException(v?.GetType().Name)
        };
        static string Struct(string name, Type type) => "struct " + name + "(" + string.Join(", ", Fields(type).Select(f => f.Name + ": " + TypeName(f.FieldType))) + ")\n";

        static void Write(StringBuilder s, object owner, string indent)
        {
            var fields = Fields(owner.GetType()).ToArray();
            for (int i = 0; i < fields.Length; i++)
            {
                object value = fields[i].GetValue(owner);
                s.Append(indent).Append(fields[i].Name).Append(": ");
                if (value is AgentUiPalette)
                {
                    s.Append("{\n");
                    Write(s, value, indent + "  ");
                    s.Append(indent).Append('}');
                }
                else
                    s.Append(Value(value));
                s.Append(i < fields.Length - 1 ? ",\n" : "\n");
            }
        }

        public static string Generate(GameTheme theme)
        {
            var s = new StringBuilder();
            s.Append("// Generated from Theme.asset in the Editor. Tune Theme.asset; do not edit this file.\n");
            s.Append("struct ").Append(ColorStruct).Append("(r: f32, g: f32, b: f32, a: f32)\n");
            s.Append(Struct(PaletteStruct, typeof(AgentUiPalette)));
            s.Append(Struct(Component, typeof(GameTheme)));
            s.Append(Entity).Append(" {\n  ").Append(Component).Append(": {\n");
            Write(s, theme, "    ");
            s.Append("  }\n}\n");
            return s.ToString();
        }

        /// <summary>Loads the script into Flecs and copies the resulting component into <paramref name="target"/>.</summary>
        public static void Load(FlecsSession session, string source, GameTheme target)
        {
            session.SetManagedScript(ScriptName, source);
            string json = session.ComponentJson(session.Lookup(Entity), Component);
            if (string.IsNullOrEmpty(json))
                throw new InvalidOperationException("Theme config script did not produce " + Component + ".");
            JsonUtility.FromJsonOverwrite(json, target);
        }

#if UNITY_EDITOR
        public static GameTheme EditorAsset => UnityEditor.AssetDatabase.LoadAssetAtPath<GameTheme>(AssetPath);

        static string Normalize(string text) => text.Replace("\r\n", "\n");

        /// <summary>Writes ThemeConfig.flecs when it differs from the asset. Returns true when the file changed.</summary>
        public static bool Export(GameTheme theme = null)
        {
            theme ??= EditorAsset;
            if (!theme)
                return false;
            string source = Generate(theme), full = System.IO.Path.GetFullPath(ScriptPath);
            if (System.IO.File.Exists(full) && Normalize(System.IO.File.ReadAllText(full)) == source)
                return false;
            System.IO.File.WriteAllText(full, source);
            UnityEditor.AssetDatabase.ImportAsset(ScriptPath);
            return true;
        }

        public static bool IsCurrent()
        {
            var theme = EditorAsset;
            return theme && System.IO.File.Exists(ScriptPath) && Normalize(System.IO.File.ReadAllText(ScriptPath)) == Generate(theme);
        }
#endif
    }
}
